const BASE = 127462 // 0x1F1E6 — regional indicator symbol for "A"

/** Turn an ISO-3166 alpha-2 code into a flag emoji (e.g. "RW" -> 🇷🇼). */
export const getFlag = (iso) => {
  if (!iso || iso.length !== 2) return '🌐'
  return String.fromCodePoint(
    ...[...iso.toUpperCase()].map((char) => BASE + (char.charCodeAt(0) - 65))
  )
}

