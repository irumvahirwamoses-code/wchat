/** Combine a dial code and a local number into a single stored value. */
export const combinePhone = (dial, local) =>
  `${dial}${String(local).replace(/\D/g, '')}`

/**
 * Split a stored phone number back into { dial, local } using the longest
 * matching dial-code prefix (falls back to the Rwandan default).
 */
export const splitPhoneNumber = (value) => {
  const raw = String(value || '').replace(/[\s-]/g, '')
  if (!raw) return { dial: DEFAULT_DIAL, local: '' }
  const normalized = raw.startsWith('+') ? raw : `+${raw}`
  const match = [...dialCodes]
    .sort((a, b) => b.dial.length - a.dial.length)
    .find((entry) => normalized.startsWith(entry.dial))
  if (!match) return { dial: DEFAULT_DIAL, local: raw.replace(/\D/g, '') }
  return { dial: match.dial, local: normalized.slice(match.dial.length).replace(/\D/g, '') }
}

export default dialCodes
